"""Support for moving a snapshot between processes, as a read-only copy of what has been loaded.

:meth:`SimSnap.get_portable_state <pynbody.snapshot.simsnap.SimSnap.get_portable_state>` expresses everything
that a snapshot has in memory -- its arrays, family structure, properties, units and any KD-tree -- as a
dictionary of numpy arrays and python primitives. The arrays can be transferred to another process, typically by
putting them into shared memory; there,
:meth:`SimSnap.from_portable_state <pynbody.snapshot.simsnap.SimSnap.from_portable_state>` turns the state back
into a :class:`PortableSimSnap`.

A :class:`PortableSimSnap` is *frozen*: it refers to the arrays it was given without copying them, and never
loads anything from disk. Arrays which the original snapshot could have loaded, but had not by the time its state
was taken, are therefore unavailable, and asking for one raises :class:`ArrayNotTransferredError`. Arrays derived
in the new process are calculated in its own memory, as normal.

Most users will not need this module directly; :class:`pynbody.ProcessPool <pynbody.parallel.ProcessPool>`
uses it to give each worker process its own copy of a snapshot. See :ref:`portable_parallelism`.

.. versionadded:: 2.9.0

"""

from __future__ import annotations

import importlib
import warnings
import weakref

import numpy as np

from .. import family, units
from .copy_on_access import UnderlyingClassMixin
from .simsnap import SimSnap

#: The version of the portable state format generated by this version of pynbody. It is incremented if a
#: change is made that older versions of pynbody cannot interpret.
PORTABLE_STATE_VERSION = 1


class ArrayNotTransferredError(KeyError):
    """Raised on asking a :class:`PortableSimSnap` for an array that was not loaded when its state was taken.

    The original snapshot could have loaded the array from disk, but a portable snapshot never touches the disk;
    the remedy is to load the array before taking the state (or before starting a
    :class:`~pynbody.parallel.ProcessPool`)."""

    def __str__(self):
        # KeyError's own __str__ shows the repr of its argument, which would wrap the explanation in quotes
        return str(self.args[0]) if self.args else ""


class ReadOnlySnapshotError(ValueError):
    """Raised on trying to modify the arrays of a :class:`PortableSimSnap`, e.g. by centring or rotating it.

    The arrays may be shared with other processes, so they are read-only. To work on part of the snapshot in a
    different frame, make a copy of that part with
    :meth:`~pynbody.snapshot.simsnap.SimSnap.get_copy_on_access_simsnap`."""


class PortableSimSnap(UnderlyingClassMixin, SimSnap):
    """A read-only snapshot, recreated from the portable state of another.

    Instances are normally created by :meth:`~pynbody.snapshot.simsnap.SimSnap.from_portable_state` rather than
    directly. They contain the arrays which had been loaded or derived in the original snapshot, and these are
    read-only. Arrays which the original could have loaded from disk but had not cannot be loaded here (see
    :class:`ArrayNotTransferredError`), but arrays can be derived, and new arrays created, as normal; these
    belong to this snapshot alone.

    .. versionadded:: 2.9.0

    """

    def __init__(self, state: dict):
        version = state.get('version', PORTABLE_STATE_VERSION)
        if version > PORTABLE_STATE_VERSION:
            raise ValueError(f"This snapshot was exported in format version {version}, but this version "
                             f"of pynbody understands only up to version {PORTABLE_STATE_VERSION}")

        super().__init__(_class_from_name(state['class']))

        from ..halo.portable import properties_from_portable_state

        self._filename = state['filename']
        self._num_particles = state['num_particles']
        self._family_slice = {family.get_family(name): slice(start, stop)
                              for name, (start, stop) in state['family_slices'].items()}
        self.properties.update(properties_from_portable_state(state['properties']))
        self._file_units_system = [units.Unit(u) for u in state['file_units_system']]
        if state['autoconvert'] is not None:
            self._autoconvert = [units.Unit(u) for u in state['autoconvert']]
        self.partial_load = state['partial_load']
        self.incomplete_file_set = state['incomplete_file_set']
        self._loadable_keys_in_original = {_family_or_none(name): keys
                                           for name, keys in state['loadable_keys'].items()}

        for name, description in state['arrays'].items():
            self._install_array(name, None, description)

        for name, by_family in state['family_arrays'].items():
            for family_name, description in by_family.items():
                self._install_array(name, family.get_family(family_name), description)

        if state.get('kdtree') is not None:
            self._attach_tree(state['kdtree'])
            if state['kdtree_derived_smoothing']:
                self._kdtree_derived_smoothing = True

    def _install_array(self, name, fam, description):
        """Install an array described in a portable state, read-only, for the whole snapshot or one family"""
        if fam is None:
            self._create_array(name, ndim=_ndim(description['data']), shared=False,
                               derived=description['derived'], source_array=_as_read_only(description))
            return

        # _create_family_array would promote a family array to a simulation array, copying it, if every family
        # then had one; that must not happen to an array which is being shared, so the array is installed directly
        source_array = _as_read_only(description)
        source_array._sim = weakref.ref(self)
        source_array._name = name
        source_array.family = fam
        self._family_arrays.setdefault(name, {})[fam] = source_array
        if description['derived']:
            self._family_derived_array_names[fam].append(name)
        if _ndim(source_array) == 3:
            for i, name_1d in enumerate(self._array_name_ND_to_1D(name)):
                view = source_array[:, i]
                view._name = name_1d
                self._family_arrays.setdefault(name_1d, {})[fam] = view

    def _attach_tree(self, tree_state, num_threads=None):
        """Recreate a KD-tree from its portable state (without particle arrays), using this snapshot's arrays"""
        from .. import kdtree
        self.kdtree = kdtree.KDTree.from_portable_state(tree_state, self['pos'], self['mass'],
                                                        num_threads=num_threads)
        self._link_tree_arrays()

    def _link_tree_arrays(self):
        """Give the tree the smoothing lengths and densities, if both exist, as the tree's own SPH operations
        (e.g. sph_mean) expect. Nothing writes to these once they exist: smoothing lengths and densities are only
        calculated afresh when they are absent, into new arrays."""
        if not hasattr(self, 'kdtree'):
            return
        for name in ('smooth', 'rho'):
            if name in self._arrays and self._arrays[name].dtype == self._arrays['pos'].dtype:
                self.kdtree.set_array_ref(name, self._arrays[name])

    def _load_array(self, array_name, fam=None):
        nd_name = self._array_name_1D_to_ND(array_name) or array_name
        if nd_name in self._loadable_keys_in_original.get(fam, []):
            where = "f" if fam is None else f"f.{fam.name}"
            raise ArrayNotTransferredError(
                f"{array_name!r} was not loaded when this snapshot was shared, so it is not available here. "
                f"Load it beforehand, e.g. by accessing {where}[{nd_name!r}] before starting the process pool.")
        raise OSError("A portable snapshot cannot load arrays")

    def loadable_keys(self, fam=None):
        """Return an empty list, since nothing can be loaded into a portable snapshot."""
        return []

    def _loadable_keys_for_portable_state(self, fam):
        return self._loadable_keys_in_original.get(fam, [])

    def _refuse_if_read_only(self, action):
        raise ReadOnlySnapshotError(
            f"This snapshot is a read-only copy (for example, one shared between processes), so it cannot be "
            f"{action}. To work on a part of it, such as a halo, in its own frame, make a modifiable copy first: "
            f"e.g. local = halo.get_copy_on_access_simsnap()")

    def _autoconvert_arrays(self, dims=None):
        dims = self._get_dims(dims)
        if dims is not None:
            for ar in self._all_arrays():
                if not ar.flags['WRITEABLE'] and units.has_units(ar) and \
                        self._cached_unit_conversion(ar.units, dims) is not None:
                    self._refuse_if_read_only("converted to different units")
        super()._autoconvert_arrays(dims)

    def _all_arrays(self):
        yield from self._arrays.values()
        for by_family in self._family_arrays.values():
            yield from by_family.values()


def snapshot_state(sim: SimSnap) -> dict:
    """Implementation of :meth:`SimSnap.get_portable_state <pynbody.snapshot.simsnap.SimSnap.get_portable_state>`"""
    from ..halo.portable import properties_to_portable_state

    if sim is not sim.ancestor:
        raise TypeError("Only a whole snapshot can be turned into a portable state, not a view of one such as a "
                        "family or a halo. Use the whole snapshot, and select the part you need afterwards.")

    families = sim.families()
    underlying_class = getattr(sim, '_underlying_class', type(sim))

    def is_view_of_nd_array(name, keys):
        nd_name = sim._array_name_1D_to_ND(name)
        return nd_name is not None and nd_name in keys

    arrays = {name: describe_array(array, name in sim._derived_array_names)
              for name, array in sim._arrays.items() if not is_view_of_nd_array(name, sim._arrays)}

    family_arrays = {}
    for name, by_family in sim._family_arrays.items():
        if is_view_of_nd_array(name, sim._family_arrays):
            continue
        family_arrays[name] = {fam.name: describe_array(array, name in sim._family_derived_array_names[fam])
                               for fam, array in by_family.items()}

    loadable_keys = {'all': list(sim._loadable_keys_for_portable_state(None))}
    for fam in families:
        loadable_keys[fam.name] = list(sim._loadable_keys_for_portable_state(fam))

    tree = getattr(sim, 'kdtree', None)
    autoconvert = sim._autoconvert

    return {'version': PORTABLE_STATE_VERSION,
            'class': f"{underlying_class.__module__}.{underlying_class.__qualname__}",
            'filename': str(sim._filename),
            'num_particles': len(sim),
            'family_slices': {fam.name: [sim._get_family_slice(fam).start, sim._get_family_slice(fam).stop]
                              for fam in families},
            'properties': properties_to_portable_state(sim.properties, description="Snapshot property"),
            'file_units_system': [units.to_exact_string(u) for u in sim._file_units_system],
            'autoconvert': None if autoconvert is None else [units.to_exact_string(u) for u in autoconvert],
            'partial_load': bool(sim.partial_load),
            'incomplete_file_set': bool(sim.incomplete_file_set),
            'loadable_keys': loadable_keys,
            'arrays': arrays,
            'family_arrays': family_arrays,
            'kdtree': None if tree is None else tree.get_portable_state(include_particle_arrays=False),
            'kdtree_derived_smoothing': bool(getattr(sim, '_kdtree_derived_smoothing', False))}


def describe_array(array, derived) -> dict:
    """Describe an array as it is stored in a portable state: the array itself, its units, and whether it is
    derived. :meth:`PortableSimSnap._install_array` turns this back into an array of a snapshot."""
    return {'data': array,
            'units': units.to_exact_string(array.units) if units.has_units(array) else None,
            'derived': derived}


def _class_from_name(name):
    module_name, _, class_name = name.rpartition(".")
    try:
        return getattr(importlib.import_module(module_name), class_name)
    except (ImportError, AttributeError):
        warnings.warn(f"Could not find the snapshot class {name}; arrays specific to it cannot be derived",
                      RuntimeWarning)
        return SimSnap


def _family_or_none(name):
    return None if name == 'all' else family.get_family(name)


def _ndim(array):
    return 1 if array.ndim == 1 else array.shape[1]


def _as_read_only(description):
    """Return a read-only SimArray for the array in a state, with the units it describes"""
    from .. import array

    # A view is taken so that the units and simulation can be set without affecting anyone else's array. It is
    # made via a plain ndarray, since a SimArray which is a view of another SimArray defers to it for its sim
    data = np.asarray(description['data']).view(array.SimArray)
    data.flags['WRITEABLE'] = False
    data.units = units.Unit(description['units']) if description['units'] is not None else units.NoUnit()
    return data
